const FontData FONT_SMALL = {6, 12, 320, sm_codepoints, sm_bitmap};
const FontData FONT_LARGE = {8, 16, 320, lg_codepoints, lg_bitmap};


static const FontData* fontAt(uint8_t i) { return i == FONT_IDX_LARGE ? &FONT_LARGE : &FONT_SMALL; }

const uint8_t* fontGlyph(uint8_t fontIndex, uint16_t codepoint) {
  const FontData& f = *fontAt(fontIndex);
  int lo = 0, hi = (int)f.count - 1;
  while (lo <= hi) {
    int mid = (lo + hi) >> 1;
    uint16_t cp = f.codepoints[mid];
    if (cp == codepoint) return f.bitmap + (size_t)mid * f.height;
    if (cp < codepoint) lo = mid + 1; else hi = mid - 1;
  }
  // Fallback to '?' directly.
  lo = 0; hi = (int)f.count - 1;
  while (lo <= hi) {
    int mid = (lo + hi) >> 1;
    uint16_t cp = f.codepoints[mid];
    if (cp == '?') return f.bitmap + (size_t)mid * f.height;
    if (cp < '?') lo = mid + 1; else hi = mid - 1;
  }
  return nullptr;
}

// Decode one UTF-8 codepoint (BMP only). Invalid input becomes '?'.
uint16_t utf8DecodeNext(const char*& p) {
  if (!p || !*p) return 0;
  uint8_t c = (uint8_t)*p++;
  if (c < 0x80) return c;
  uint8_t need = 0;
  uint32_t cp = 0;
  if ((c & 0xE0) == 0xC0) { need = 1; cp = c & 0x1F; }
  else if ((c & 0xF0) == 0xE0) { need = 2; cp = c & 0x0F; }
  else if ((c & 0xF8) == 0xF0) { need = 3; cp = c & 0x07; }
  else return '?';
  for (uint8_t i = 0; i < need; ++i) {
    if (((uint8_t)*p & 0xC0) != 0x80) return '?';
    cp = (cp << 6) | ((uint8_t)*p++ & 0x3F);
  }
  return cp > 0xFFFF ? (uint16_t)'?' : (uint16_t)cp;
}

size_t utf8Length(const char* text) {
  size_t n = 0;
  const char* p = text;
  while (*p) { utf8DecodeNext(p); ++n; }
  return n;
}

int fontTextWidth(uint8_t fontIndex, const char* text) {
  const FontData& f = *fontAt(fontIndex);
  int n = 0;
  const char* p = text;
  while (*p) { utf8DecodeNext(p); ++n; }
  return n * f.width;
}

int fontTextWidthN(uint8_t fontIndex, const char* text, int maxChars) {
  const FontData& f = *fontAt(fontIndex);
  const char* p = text;
  int n = 0;
  while (*p && n < maxChars) { utf8DecodeNext(p); ++n; }
  return n * f.width;
}


